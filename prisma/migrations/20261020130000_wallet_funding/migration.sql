CREATE TABLE IF NOT EXISTS "wallet_funding" (
  "id" TEXT NOT NULL PRIMARY KEY,
  "companyId" TEXT NOT NULL REFERENCES "companies"("id") ON DELETE RESTRICT ON UPDATE CASCADE,
  "initiatedBy" TEXT NOT NULL,
  "amountCentavos" INTEGER NOT NULL,
  "feePolicy" TEXT NOT NULL,
  "parentAccountId" TEXT NOT NULL,
  "accountId" TEXT NOT NULL,
  "walletId" TEXT NOT NULL,
  "livemode" BOOLEAN NOT NULL,
  "sourceAccount" JSONB NOT NULL,
  "destinationAccount" JSONB NOT NULL,
  "status" TEXT NOT NULL DEFAULT 'CREATING',
  "checkoutId" TEXT UNIQUE,
  "checkoutUrl" TEXT,
  "paymentId" TEXT UNIQUE,
  "payoutId" TEXT,
  "payoutCursor" TEXT,
  "netCentavos" INTEGER,
  "creditCentavos" INTEGER,
  "batchId" TEXT UNIQUE,
  "transferId" TEXT UNIQUE,
  "transferFee" INTEGER,
  "payload" JSONB,
  "error" TEXT,
  "checkedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "processingUntil" TIMESTAMP(3),
  "completedAt" TIMESTAMP(3),
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMP(3) NOT NULL,
  CONSTRAINT "wallet_funding_amount" CHECK ("amountCentavos" > 0),
  CONSTRAINT "wallet_funding_credit" CHECK ("creditCentavos" > 0 AND "creditCentavos" <= "amountCentavos")
);
CREATE INDEX IF NOT EXISTS "wallet_funding_companyId_createdAt_idx" ON "wallet_funding"("companyId", "createdAt");
CREATE INDEX IF NOT EXISTS "wallet_funding_status_checkedAt_idx" ON "wallet_funding"("status", "checkedAt");
